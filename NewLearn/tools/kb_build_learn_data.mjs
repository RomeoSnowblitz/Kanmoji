// Packs each NewLearn vocabulary and sentence file once. Each row keeps the text and only the
// first link in every other language, which is the only link a lesson uses.
// The Learn pages build a language pair from these banks when a lesson opens.
// Alphabet scripts stay as pair files; they are copied from OldLearn/data and are tiny.
// A pair is UI language then learned language: en-zh means the prompt is English and the answer is Chinese.
import fs from 'fs';
import readline from 'readline';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const newRoot = path.resolve(here, '..');
const appRoot = path.resolve(newRoot, '..');
const outDir = path.join(newRoot, 'data');
const oldAlphabet = path.join(appRoot, 'OldLearn', 'data');

const letters = ['C', 'E', 'F', 'G', 'I', 'J', 'K', 'P', 'R', 'S'];
const files = {
  C: 'Chinese', E: 'English', F: 'French', G: 'German', I: 'Italian',
  J: 'Japanese', K: 'Korean', P: 'Portuguese', R: 'Russian', S: 'Spanish'
};
const codes = {
  C: 'zh', E: 'en', F: 'fr', G: 'de', I: 'it',
  J: 'ja', K: 'ko', P: 'pt', R: 'ru', S: 'es'
};

function js(s) {
  return '"' + String(s)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029') + '"';
}

const lineRx = /^(.*) \(([^()]*)\) \(([A-Z]*)\)$/;

// A lesson uses only the first link in each other language, so the bank keeps that number and drops the rest.
function packLine(line) {
  const match = lineRx.exec(line);
  if (!match) return line.replace(/\u001f/g, ' ');
  const seen = new Set();
  const parts = [];
  if (match[2]) {
    for (const token of match[2].split(', ')) {
      if (!token) continue;
      const letter = token[0];
      if (seen.has(letter)) continue;
      let n = 0;
      let any = false;
      for (let j = 1; j < token.length; j++) {
        const c = token.charCodeAt(j);
        if (c < 48 || c > 57) { any = false; break; }
        any = true;
        n = n * 10 + (c - 48);
      }
      if (!any || !n) continue;
      seen.add(letter);
      parts.push(letter + String(n));
    }
  }
  return match[1].replace(/\u001f/g, ' ') + '\u001f' + parts.join('\t');
}

async function writeBank(kind, letter) {
  const code = codes[letter];
  const prefix = kind === 'Vocabulary' ? 'vocab' : 'sentence';
  const key = prefix + '-' + code;
  const src = path.join(newRoot, kind, files[letter] + '.txt');
  const dest = path.join(outDir, 'bank-' + key + '.js');
  const rl = readline.createInterface({
    input: fs.createReadStream(src, { encoding: 'utf8' }),
    crlfDelay: Infinity
  });
  const ws = fs.createWriteStream(dest, { encoding: 'utf8' });
  const closed = new Promise((resolve, reject) => {
    ws.on('finish', resolve);
    ws.on('error', reject);
  });
  ws.write('/* Generated by NewLearn/tools/kb_build_learn_data.mjs. Do not edit by hand. */\n');
  ws.write('window.LEARN_BANK = window.LEARN_BANK || {};\n');
  ws.write('window.LEARN_BANK[' + js(key) + '] = [\n');
  let first = true;
  let rows = 0;
  for await (const line of rl) {
    if (!line) continue;
    if (line.charCodeAt(0) === 0xFEFF) throw new Error('BOM ' + src);
    const chunk = (first ? '' : ',\n') + JSON.stringify(packLine(line));
    first = false;
    rows++;
    if (!ws.write(chunk)) await new Promise((resolve) => ws.once('drain', resolve));
  }
  if (!ws.write('\n];\n')) await new Promise((resolve) => ws.once('drain', resolve));
  ws.end();
  await closed;
  console.log(key + ': ' + rows + ' rows');
}

function copyAlphabet() {
  if (!fs.existsSync(oldAlphabet)) {
    console.log('alphabet scripts already in data');
    return;
  }
  const names = fs.readdirSync(oldAlphabet).filter((name) => name.startsWith('alphabet-') && name.endsWith('.js'));
  for (const name of names) fs.copyFileSync(path.join(oldAlphabet, name), path.join(outDir, name));
  console.log('alphabet scripts copied: ' + names.length);
}

function countFile(file) {
  const text = fs.readFileSync(file);
  let n = 0;
  for (let i = 0; i < text.length; i++) if (text[i] === 10) n++;
  if (text.length && text[text.length - 1] !== 10) n++;
  return n;
}

// One total per learned language. Alphabet size is the unique letters in the English-UI file
// (Chinese-UI for English, which has no English-UI alphabet file).
function countAlphabet(code) {
  const fileCode = { zh: 'ZH', en: 'EN', fr: 'FR', de: 'DE', it: 'IT', ja: 'JP', ko: 'KO', pt: 'PO', ru: 'RU', es: 'ES' }[code];
  const file = code === 'en'
    ? path.join(newRoot, 'Alphabet', 'Chinese', 'ZH-EN.txt')
    : path.join(newRoot, 'Alphabet', 'English', 'EN-' + fileCode + '.txt');
  if (!fs.existsSync(file)) return 0;
  const seen = new Set();
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line.startsWith(' ')) continue;
    const left = line.slice(1).split(' - ')[0].trim();
    if (left && left.toLowerCase() !== 'null') seen.add(left);
  }
  return seen.size;
}

function countTotals() {
  const counts = { alphabet: {}, vocabulary: {}, sentence: {} };
  for (const letter of letters) {
    const code = codes[letter];
    counts.alphabet[code] = countAlphabet(code);
    counts.vocabulary[code] = countFile(path.join(newRoot, 'Vocabulary', files[letter] + '.txt'));
    counts.sentence[code] = countFile(path.join(newRoot, 'Sentences', files[letter] + '.txt'));
  }
  return counts;
}

function writeReady() {
  const ready = { alphabet: [], vocabulary: [], sentence: [] };
  const pairs = [];
  for (const ui of letters) {
    for (const learned of letters) {
      if (ui !== learned) pairs.push(codes[ui] + '-' + codes[learned]);
    }
  }
  ready.vocabulary = pairs.slice();
  ready.sentence = pairs.slice();
  for (const name of fs.readdirSync(outDir)) {
    const m = /^alphabet-([a-z]{2}-[a-z]{2})\.js$/.exec(name);
    if (m) ready.alphabet.push(m[1]);
  }
  for (const key of Object.keys(ready)) ready[key].sort();
  const list = (pairs) => pairs.map((p) => '"' + p + '"').join(',');
  const counts = countTotals();
  const countLine = (kind) => letters.map((letter) => codes[letter] + ':' + counts[kind][codes[letter]]).join(',');
  const manifest = '/* Generated by NewLearn/tools/kb_build_learn_data.mjs: the UI-language/learned-language pairs that have data. */\n' +
    'window.LEARN_READY = {\n' +
    '  alphabet: [' + list(ready.alphabet) + '],\n' +
    '  vocabulary: [' + list(ready.vocabulary) + '],\n' +
    '  sentence: [' + list(ready.sentence) + ']\n' +
    '};\n' +
    'window.LEARN_COUNTS = {\n' +
    '  alphabet: {' + countLine('alphabet') + '},\n' +
    '  vocabulary: {' + countLine('vocabulary') + '},\n' +
    '  sentence: {' + countLine('sentence') + '}\n' +
    '};\n';
  fs.writeFileSync(path.join(outDir, 'ready.js'), manifest);
  console.log('ready.js: ' + ready.alphabet.length + ' alphabet, ' + ready.vocabulary.length + ' vocabulary, ' + ready.sentence.length + ' sentence');
}

if (process.argv.includes('--counts-only')) {
  writeReady();
} else {
  fs.mkdirSync(outDir, { recursive: true });
  copyAlphabet();
  for (const kind of ['Vocabulary', 'Sentences']) {
    for (const letter of letters) await writeBank(kind, letter);
  }
  writeReady();
}
