// Packs NewLearn/Vocabulary and NewLearn/Sentences into the lesson scripts the Learn pages load.
// Alphabet scripts are copied from OldLearn/data (the alphabet files were copied and did not change).
// A pair is UI language then learned language: en-zh means the prompt is English and the answer is Chinese.
// Lessons follow the learned language's file order. Each row is "answer \t reading \t prompt".
// The prompt is the first linked line in the UI language, which is the earliest taught translation.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const newRoot = path.resolve(here, '..');
const appRoot = path.resolve(newRoot, '..');
const outDir = path.join(newRoot, 'data');
const oldAlphabet = path.join(appRoot, 'OldLearn', 'data');

const letters = ['C', 'E', 'F', 'G', 'I', 'J', 'K', 'P', 'R', 'S'];
const files = {
  C: 'Chinese', E: 'English', F: 'French', G: 'German', I: 'Italian',
  J: 'Japanese', K: 'Korean', P: 'Portuguese', R: 'Russian', S: 'Spanish'
};
const codes = {
  C: 'zh', E: 'en', F: 'fr', G: 'de', I: 'it',
  J: 'ja', K: 'ko', P: 'pt', R: 'ru', S: 'es'
};

const VOCAB_SIZE = 25;
const SENTENCE_SIZE = 40;
const rx = /^(.*) \(([^()]*)\) \(([A-Z]*)\)$/;

function js(s) {
  return '"' + String(s)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029') + '"';
}

function readBank(file) {
  let s = fs.readFileSync(file, 'utf8');
  if (s.charCodeAt(0) === 0xFEFF) throw new Error('BOM ' + file);
  if (s.endsWith('\r\n')) s = s.slice(0, -2);
  else if (s.endsWith('\n')) s = s.slice(0, -1);
  return s.split(/\r?\n/).map((line, i) => {
    const m = rx.exec(line);
    if (!m) throw new Error('Unparsed ' + file + ' line ' + (i + 1));
    const links = {};
    if (m[2]) {
      for (const id of m[2].split(', ')) {
        if (!id) continue;
        const L = id[0];
        const n = Number(id.slice(1));
        if (!links[L]) links[L] = [];
        links[L].push(n);
      }
    }
    return { text: m[1], links };
  });
}

function load(kind) {
  const banks = {};
  for (const L of letters) {
    const file = path.join(newRoot, kind, files[L] + '.txt');
    banks[L] = readBank(file);
    console.log(kind + ' ' + files[L] + ': ' + banks[L].length + ' rows');
  }
  return banks;
}

function promptOf(banks, ui, row) {
  const nums = row.links[ui];
  if (!nums || !nums.length) return '';
  const other = banks[ui][nums[0] - 1];
  return other ? other.text : '';
}

function lessonName(text) {
  const name = text.replace(/\s+/g, ' ').trim();
  return name.length > 36 ? name.slice(0, 35) + '...' : name;
}

class PairWriter {
  constructor(file, globalName, pair) {
    this.file = file;
    this.ws = fs.createWriteStream(file, { encoding: 'utf8' });
    this.ws.setMaxListeners(0);
    this.ws.on('error', (err) => { this.failed = err; });
    this.header = '/* Generated by NewLearn/tools/kb_build_learn_data.mjs. Do not edit by hand. */\n' +
      'window.' + globalName + ' = window.' + globalName + ' || {};\n' +
      'window.' + globalName + '["' + pair + '"] = [\n';
    this.started = false;
    this.rows = [];
    this.name = '';
    this.lessons = 0;
    this.count = 0;
    this.skipped = 0;
    this.first = true;
    this.failed = null;
  }
  async write(chunk) {
    if (this.failed) throw this.failed;
    if (!this.started) {
      this.started = true;
      chunk = this.header + chunk;
    }
    if (this.ws.write(chunk)) return;
    await new Promise((resolve) => this.ws.once('drain', resolve));
    if (this.failed) throw this.failed;
  }
  async add(text, meaning) {
    if (!this.rows.length) this.name = lessonName(text);
    this.rows.push(js(text + '\t\t' + meaning));
    this.count++;
    if (this.rows.length >= this.size) await this.flush();
  }
  async flush() {
    if (!this.rows.length) return;
    const line = (this.first ? '' : ',\n') + '  [' + js(this.name) + ',[' + this.rows.join(',') + ']]';
    this.first = false;
    this.rows = [];
    this.name = '';
    this.lessons++;
    await this.write(line);
  }
  async end() {
    await this.flush();
    await this.write('\n];\n');
    await new Promise((resolve, reject) => {
      this.ws.end(resolve);
      this.ws.once('error', reject);
    });
  }
}

async function build(kind, globalName, prefix, size) {
  const banks = load(kind);
  let rows = 0;
  let skipped = 0;
  for (const learned of letters) {
    const writers = [];
    for (const ui of letters) {
      if (ui === learned) continue;
      const pair = codes[ui] + '-' + codes[learned];
      const w = new PairWriter(path.join(outDir, prefix + '-' + pair + '.js'), globalName, pair);
      w.ui = ui;
      w.size = size;
      writers.push(w);
    }
    for (const row of banks[learned]) {
      for (const w of writers) {
        const meaning = promptOf(banks, w.ui, row);
        if (!meaning) { w.skipped++; continue; }
        await w.add(row.text, meaning);
      }
    }
    for (const w of writers) {
      await w.end();
      rows += w.count;
      skipped += w.skipped;
      console.log(prefix + ' ' + codes[w.ui] + '-' + codes[learned] + ': ' + w.lessons + ' lessons, ' + w.count + ' rows, ' + w.skipped + ' skipped');
    }
  }
  console.log(kind + ' done: ' + rows + ' rows, ' + skipped + ' skipped');
}

function copyAlphabet() {
  const names = fs.readdirSync(oldAlphabet).filter((name) => name.startsWith('alphabet-') && name.endsWith('.js'));
  for (const name of names) fs.copyFileSync(path.join(oldAlphabet, name), path.join(outDir, name));
  console.log('alphabet scripts copied: ' + names.length);
}

function countFile(file) {
  const text = fs.readFileSync(file);
  let n = 0;
  for (let i = 0; i < text.length; i++) if (text[i] === 10) n++;
  if (text.length && text[text.length - 1] !== 10) n++;
  return n;
}

// One total per learned language. Alphabet size is the unique letters in the English-UI file
// (Chinese-UI for English, which has no English-UI alphabet file).
function countAlphabet(code) {
  const fileCode = { zh: 'ZH', en: 'EN', fr: 'FR', de: 'DE', it: 'IT', ja: 'JP', ko: 'KO', pt: 'PO', ru: 'RU', es: 'ES' }[code];
  const file = code === 'en'
    ? path.join(newRoot, 'Alphabet', 'Chinese', 'ZH-EN.txt')
    : path.join(newRoot, 'Alphabet', 'English', 'EN-' + fileCode + '.txt');
  if (!fs.existsSync(file)) return 0;
  const seen = new Set();
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line.startsWith(' ')) continue;
    const left = line.slice(1).split(' - ')[0].trim();
    if (left && left.toLowerCase() !== 'null') seen.add(left);
  }
  return seen.size;
}

function countTotals() {
  const counts = { alphabet: {}, vocabulary: {}, sentence: {} };
  for (const letter of letters) {
    const code = codes[letter];
    counts.alphabet[code] = countAlphabet(code);
    counts.vocabulary[code] = countFile(path.join(newRoot, 'Vocabulary', files[letter] + '.txt'));
    counts.sentence[code] = countFile(path.join(newRoot, 'Sentences', files[letter] + '.txt'));
  }
  return counts;
}

function writeReady() {
  const ready = { alphabet: [], vocabulary: [], sentence: [] };
  for (const name of fs.readdirSync(outDir)) {
    let m = /^alphabet-([a-z]{2}-[a-z]{2})\.js$/.exec(name);
    if (m) ready.alphabet.push(m[1]);
    m = /^vocab-([a-z]{2}-[a-z]{2})\.js$/.exec(name);
    if (m) ready.vocabulary.push(m[1]);
    m = /^sentence-([a-z]{2}-[a-z]{2})\.js$/.exec(name);
    if (m) ready.sentence.push(m[1]);
  }
  for (const key of Object.keys(ready)) ready[key].sort();
  const list = (pairs) => pairs.map((p) => '"' + p + '"').join(',');
  const counts = countTotals();
  const countLine = (kind) => letters.map((letter) => codes[letter] + ':' + counts[kind][codes[letter]]).join(',');
  const manifest = '/* Generated by NewLearn/tools/kb_build_learn_data.mjs: the UI-language/learned-language pairs that have data. */\n' +
    'window.LEARN_READY = {\n' +
    '  alphabet: [' + list(ready.alphabet) + '],\n' +
    '  vocabulary: [' + list(ready.vocabulary) + '],\n' +
    '  sentence: [' + list(ready.sentence) + ']\n' +
    '};\n' +
    'window.LEARN_COUNTS = {\n' +
    '  alphabet: {' + countLine('alphabet') + '},\n' +
    '  vocabulary: {' + countLine('vocabulary') + '},\n' +
    '  sentence: {' + countLine('sentence') + '}\n' +
    '};\n';
  fs.writeFileSync(path.join(outDir, 'ready.js'), manifest);
  console.log('ready.js: ' + ready.alphabet.length + ' alphabet, ' + ready.vocabulary.length + ' vocabulary, ' + ready.sentence.length + ' sentence');
}

if (process.argv.includes('--counts-only')) {
  writeReady();
} else {
  fs.mkdirSync(outDir, { recursive: true });
  copyAlphabet();
  await build('Vocabulary', 'LEARN_VOCAB', 'vocab', VOCAB_SIZE);
  await build('Sentences', 'LEARN_SENTENCES', 'sentence', SENTENCE_SIZE);
  writeReady();
}
